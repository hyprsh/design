// Vendors the Lucide icon set (ISC) into project/components/src/_icons.js for the Icon component.
// Usage: node scripts/icons.mjs
// Downloads lucide-static@VERSION with `npm pack` into .cache/ and reads only its SVG files.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const VERSION = '1.49.0';
const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const CACHE = join(ROOT, '.cache', `lucide-static-${VERSION}`);
const SRC = join(ROOT, 'project/components/src');

if (!existsSync(join(CACHE, 'package/icons'))) {
  mkdirSync(CACHE, { recursive: true });
  const tgz = execFileSync('npm', ['pack', `lucide-static@${VERSION}`, '--silent', '--pack-destination', CACHE], { encoding: 'utf8' }).trim().split('\n').pop();
  execFileSync('tar', ['-xzf', join(CACHE, tgz), '-C', CACHE, 'package/icons', 'package/LICENSE']);
}

const dir = join(CACHE, 'package/icons');
const icons = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith('.svg')).sort()) {
  const svg = readFileSync(join(dir, f), 'utf8').replace(/<!--[\s\S]*?-->/g, '');
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '')
    .replace(/\s*\n\s*/g, '').trim();
  if (!/^(<(path|circle|rect|line|polyline|polygon|ellipse)\b[^<>]*\/>)+$/.test(inner)) {
    console.warn('skip (unexpected markup):', f);
    continue;
  }
  icons[f.slice(0, -4)] = inner;
}

const licence = readFileSync(join(CACHE, 'package/LICENSE'), 'utf8').replace(/\*\//g, '* /').trim();
const out = `/* Icons: Lucide ${VERSION} (https://lucide.dev). Generated by scripts/icons.mjs; do not edit.\n\n${licence}\n*/
var ICONS = ${JSON.stringify(icons)};
`;
writeFileSync(join(SRC, '_icons.js'), out);
writeFileSync(join(SRC, 'LUCIDE-LICENSE.txt'), readFileSync(join(CACHE, 'package/LICENSE'), 'utf8'));
console.log(`${Object.keys(icons).length} icons · ${(out.length / 1024).toFixed(0)} KB`);
