// Builds the npm package in dist/ from the same sources as the artifact bundle:
//   dist/index.js     ES module: every component as a named export, React and ReactDOM imported
//   dist/index.d.ts   types
//   dist/styles.css   component styles, inside @layer hyprsh
//   dist/tokens.css   tokens, type classes and @font-face (fonts in dist/fonts)
//   dist/tailwind.css Tailwind v4 entry: tokens, @theme mapping, dark variant, type utilities, components, base
//   dist/icons.js     opt-in: registers the full Lucide set for <Icon name="…">
//   dist/brand/       logo SVGs
// Dark mode follows [data-theme="dark"] or a .dark class on any ancestor.
// Usage: node scripts/package.mjs
import { readFileSync, writeFileSync, mkdirSync, rmSync, readdirSync, copyFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from './build.mjs';
import { compileTokens, typeStyles } from './tokens-css.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const PROJECT = join(ROOT, 'project');
const SRC = join(PROJECT, 'components/src');
const DIST = join(ROOT, 'dist');
const read = (p) => readFileSync(p, 'utf8');
const indent = (s, pad) => s.split('\n').map((l) => (l ? pad + l : l)).join('\n');
const themed = (css) => css
  .replaceAll('[data-theme="dark"]', ':is([data-theme="dark"], .dark)')
  .replaceAll('[data-theme="light"]', ':is([data-theme="light"], .light)');

const ramps = ['gray', 'gray-alpha', 'blue', 'green', 'amber', 'red', 'purple', 'pink', 'teal', 'accent'];
// Tailwind radius names that mean the same as the design's, so mapping them changes no pixel.
const radii = ['sm', 'md', 'lg', 'xl', '2xl'];

// Splits core.css into the document-level rules (colour-scheme, body, ::selection) and the rest.
function splitCore(core) {
  const at = core.indexOf('.hy-sr {');
  if (at < 0 || !core.startsWith('/*') || !core.includes('body {')) throw new Error('core.css: could not find the base rules before .hy-sr');
  const nl = core.indexOf('\n') + 1;
  return { base: core.slice(nl, at).trim(), rest: core.slice(at).trim() };
}

// dist/tailwind.css: everything a Tailwind v4 app needs from the design in one import.
function tailwindEntry(t, { tokens, components, base }) {
  const names = new Set(t.color.tokens.map((c) => c.name));
  const colors = [];
  for (const r of ramps) {
    for (let i = 100; i <= 1000; i += i < 1000 ? 100 : 0) {
      const n = `${r}-${i}`;
      if (!names.has(n)) throw new Error(`tokens.json: no colour ${n}`);
      colors.push(`  --color-${n}: var(--${n});`);
      if (i === 1000) break;
    }
  }
  const bg = ['background-100', 'background-200'].map((n) => {
    if (!names.has(n)) throw new Error(`tokens.json: no colour ${n}`);
    return `  --color-${n}: var(--${n});`;
  });
  const rad = radii.map((n) => {
    if (!t.radius.tokens.some((c) => c.name === 'radius-' + n)) throw new Error(`tokens.json: no radius-${n}`);
    return `  --radius-${n}: var(--radius-${n});`;
  });
  const shadows = t.shadow.tokens.map((c) => `  --${c.name}: var(--${c.name});`);
  const utilities = typeStyles(t).map(([name, decl]) => `@utility ${name} {\n  ${decl.replaceAll('; ', ';\n  ')}\n}`);
  const indent2 = (s) => indent(s, '  ');
  return [
    '/* @hyprsh/design for Tailwind v4: generated by scripts/package.mjs; do not edit.',
    '   Use it after Tailwind:  @import "tailwindcss";  @import "@hyprsh/design/tailwind.css"; */',
    '',
    '/* Tokens and fonts stay unlayered: custom properties ignore layers. */',
    tokens.trim(),
    '',
    '/* Tailwind names for the design\'s tokens. "inline" keeps utilities pointing at the token variables, so themes still switch. */',
    '@theme inline {',
    `  --font-sans: ${t.type.families.sans};`,
    `  --font-mono: ${t.type.families.mono};`,
    '',
    ...bg, '', ...colors, '', ...rad, '', ...shadows,
    '}',
    '',
    '@custom-variant dark (&:where(.dark, .dark *, [data-theme="dark"], [data-theme="dark"] *));',
    '',
    '/* Type styles as utilities, so they take variants: md:label-14 */',
    utilities.join('\n'),
    '',
    '@layer base {',
    indent2(base),
    '}',
    '',
    '/* Below utilities, so a class on a component\'s element wins without !important. */',
    '@layer components {',
    indent2(components),
    '}',
    '',
  ].join('\n');
}

export function buildPackage() {
  const { order, errors } = build({ write: false });
  if (errors.length) throw new Error(errors.join('\n'));

  const core = read(join(SRC, 'core.js')).replace(/^var React = window\.React;\nvar ReactDOM = window\.ReactDOM;\n/m, '');
  if (/window\.React/.test(core)) throw new Error('core.js: could not strip the window.React globals');

  // Only the icons the components name ship in the main entry; dist/icons.js adds the rest.
  const ICONS = new Function(read(join(SRC, '_icons.js')) + '\nreturn ICONS;')();
  const used = new Set();
  for (const n of order) for (const m of read(join(SRC, n + '.js')).matchAll(/'([a-z0-9-]+)'/g)) if (ICONS[m[1]]) used.add(m[1]);
  const subset = Object.fromEntries([...used].sort().map((k) => [k, ICONS[k]]));

  const defined = [...new Set(order.flatMap((n) => [...read(join(SRC, n + '.js')).matchAll(/define\('([A-Za-z]+)'/g)].map((m) => m[1])))].sort();

  const js = [
    '/* @hyprsh/design: generated by scripts/package.mjs; do not edit. Icons: Lucide (ISC), see LUCIDE-LICENSE.txt. */',
    "import * as React from 'react';",
    "import * as ReactDOM from 'react-dom';",
    '',
    core.trim(),
    `var ICONS = ${JSON.stringify(subset)};`,
    '',
    ...order.map((n) => `/* ---- ${n} ---- */\n(function () {\n${indent(read(join(SRC, n + '.js')).trim(), '  ')}\n})();\n`),
    // Aliased so that exports such as Error never shadow globals inside this module.
    ...defined.map((n) => `var __hy_${n} = HY.${n};`),
    `var __hy_registerIcons = HY.Icon.register;`,
    `export { ${defined.map((n) => `__hy_${n} as ${n}`).join(', ')}, __hy_registerIcons as registerIcons, HY as Hyprsh };`,
    '',
  ].join('\n');

  const tokensJson = JSON.parse(read(join(PROJECT, 'tokens.json')));
  const bundle = themed(read(join(PROJECT, 'components/bundle.css'))).trim();
  const css = `@layer hyprsh {\n${bundle}\n}\n`;
  const withClasses = (c) => c
    .replace(':root, [data-theme="light"] {', ':root, [data-theme="light"], .light {')
    .replace('[data-theme="dark"] {', '[data-theme="dark"], .dark {');
  const tokens = withClasses(compileTokens(tokensJson));

  // Tailwind entry: the document rules go to its base layer, the rest of the components to components.
  const split = splitCore(bundle);
  const tailwind = tailwindEntry(tokensJson, {
    tokens: withClasses(compileTokens(tokensJson, '', { classes: false })),
    base: split.base,
    components: `@layer hyprsh {\n${split.rest}\n}`,
  });

  const dts = [
    read(join(SRC, 'core.d.ts')).trim(),
    ...order.map((n) => read(join(SRC, n + '.d.ts')).trim()),
    '/** Adds icons for <Icon name="…">: a map of Lucide names to SVG inner markup. */',
    'export declare function registerIcons(map: Record<string, string>): void;',
    '/** Every component by name, as window.Hyprsh holds them in the artifact bundle. */',
    `export declare const Hyprsh: {\n${defined.map((n) => `  ${n}: typeof ${n};`).join('\n')}\n};`,
    '',
  ].join('\n\n');
  const missing = defined.filter((n) => !new RegExp(`export declare (const|function) ${n}\\b`).test(dts));
  if (missing.length) throw new Error('index.d.ts: no declaration for ' + missing.join(', '));

  rmSync(DIST, { recursive: true, force: true });
  mkdirSync(join(DIST, 'fonts'), { recursive: true });
  mkdirSync(join(DIST, 'brand'), { recursive: true });
  writeFileSync(join(DIST, 'index.js'), js);
  writeFileSync(join(DIST, 'index.d.ts'), dts);
  writeFileSync(join(DIST, 'styles.css'), css);
  writeFileSync(join(DIST, 'tokens.css'), tokens);
  writeFileSync(join(DIST, 'tailwind.css'), tailwind);
  writeFileSync(join(DIST, 'icons.js'), `/* Registers every Lucide icon (ISC) for <Icon name="…">. Generated; do not edit. */\nimport { registerIcons } from './index.js';\nregisterIcons(${JSON.stringify(ICONS)});\n`);
  writeFileSync(join(DIST, 'icons.d.ts'), 'export {};\n');
  for (const f of readdirSync(join(PROJECT, 'fonts'))) copyFileSync(join(PROJECT, 'fonts', f), join(DIST, 'fonts', f));
  for (const f of readdirSync(join(PROJECT, 'brand'))) copyFileSync(join(PROJECT, 'brand', f), join(DIST, 'brand', f));
  copyFileSync(join(SRC, 'LUCIDE-LICENSE.txt'), join(DIST, 'LUCIDE-LICENSE.txt'));
  if (!existsSync(join(DIST, 'index.js'))) throw new Error('dist/index.js was not written');
  return { components: defined.length, icons: used.size, js: js.length, css: css.length, tailwind: tailwind.length };
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const r = buildPackage();
  console.log(`dist/ · ${r.components} exports · ${r.icons} icons in the main entry · index.js ${(r.js / 1024).toFixed(1)} KB · styles.css ${(r.css / 1024).toFixed(1)} KB · tailwind.css ${(r.tailwind / 1024).toFixed(1)} KB`);
}
